// ===================== CO-OWNERS =====================
function CoOwnersView({ server }: { server: Server }) {
  const [, forceUpdate] = useState(0);
  const [email, setEmail] = useState("");
  const [error, setError] = useState("");

  useEffect(() => subscribeStore(() => forceUpdate(n => n + 1)), []);

  const add = () => {
    if (!email || !/\S+@\S+\.\S+/.test(email)) { setError("Введите корректный email"); return; }
    addCoOwner(server.id, email);
    setEmail("");
    setError("");
  };

  return (
    <div className="h-full overflow-y-auto">
      <h3 className="text-white font-bold font-montserrat mb-6">Совладельцы</h3>
      <div className="gradient-card rounded-xl p-5 mb-4">
        <label className="text-white/50 text-xs mb-2 block">Добавить по email</label>
        <div className="flex gap-2">
          <input value={email} onChange={e => setEmail(e.target.value)} placeholder="friend@email.com"
            className="flex-1 px-3 py-2.5 rounded-xl bg-white/5 border border-white/10 text-white text-sm focus:outline-none focus:border-green-500" />
          <button onClick={add} className="btn-primary px-4 py-2 rounded-xl text-white text-sm font-semibold">
            <Icon name="UserPlus" size={15} />
          </button>
        </div>
        {error && <p className="text-red-400 text-xs mt-1">{error}</p>}
      </div>
      <div className="space-y-2">
        {server.coOwners.length === 0 ? (
          <p className="text-white/30 text-sm text-center py-8">Нет совладельцев</p>
        ) : (
          server.coOwners.map(e => (
            <div key={e} className="flex items-center gap-3 px-4 py-3 rounded-xl gradient-card">
              <Icon name="User" size={16} className="text-green-400" />
              <span className="text-white text-sm flex-1">{e}</span>
              <button onClick={() => removeCoOwner(server.id, e)} className="text-white/40 hover:text-red-400 transition-colors">
                <Icon name="X" size={15} />
              </button>
            </div>
          ))
        )}
      </div>
    </div>
  );
}

