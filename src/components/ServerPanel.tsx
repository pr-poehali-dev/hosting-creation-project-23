// ===================== FILES =====================
function FilesView() {
  const [files, setFiles] = useState<ServerFile[]>(defaultFiles);
  const [viewing, setViewing] = useState<string | null>(null);
  const [editContent, setEditContent] = useState(defaultServerProps);
  const inputRef = useRef<HTMLInputElement>(null);

  const deleteFile = (name: string) => setFiles(f => f.filter(x => x.name !== name));

  const uploadFile = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    const ext = file.name.split(".").pop()?.toLowerCase() || "other";
    const type: ServerFile["type"] = (["jar", "jpg", "png", "txt", "json", "yml"].includes(ext) ? ext : "other") as ServerFile["type"];
    setFiles(f => [...f, { name: file.name, type, size: `${(file.size / 1024).toFixed(1)} KB` }]);
    e.target.value = "";
  };

  return (
    <div className="h-full flex flex-col">
      <div className="flex items-center justify-between mb-4 flex-shrink-0">
        <h3 className="text-white font-bold font-montserrat">Файлы сервера</h3>
        <button onClick={() => inputRef.current?.click()}
          className="flex items-center gap-2 px-4 py-2 rounded-lg text-sm font-semibold text-white btn-primary">
          <Icon name="Upload" size={14} /> Загрузить
        </button>
        <input ref={inputRef} type="file" accept=".jar,.jpg,.jpeg,.png,.txt,.json,.yml,.yaml,.properties" className="hidden" onChange={uploadFile} />
      </div>

      {viewing ? (
        <div className="flex-1 flex flex-col">
          <div className="flex items-center gap-3 mb-3">
            <button onClick={() => setViewing(null)} className="text-white/50 hover:text-white"><Icon name="ArrowLeft" size={16} /></button>
            <span className="text-white font-mono text-sm">{viewing}</span>
          </div>
          <textarea value={editContent} onChange={e => setEditContent(e.target.value)}
            className="flex-1 bg-[#1a1f2e] border border-white/10 rounded-xl p-4 text-white font-mono text-sm resize-none focus:outline-none focus:border-green-500"
          />
          <button onClick={() => setViewing(null)} className="mt-3 btn-primary px-6 py-2 rounded-xl text-white font-semibold text-sm self-end">
            Сохранить
          </button>
        </div>
      ) : (
        <div className="flex-1 overflow-y-auto">
          <div className="space-y-2">
            {files.map(f => (
              <div key={f.name} className="flex items-center gap-3 px-4 py-3 rounded-xl gradient-card hover:bg-white/5 transition-colors">
                <Icon name={fileIcon(f.type)} size={18} className="text-green-400 flex-shrink-0" />
                <span className="text-white text-sm flex-1 font-mono">{f.name}</span>
                <span className="text-white/30 text-xs">{f.size}</span>
                <button onClick={() => { setViewing(f.name); setEditContent(defaultServerProps); }}
                  className="text-white/40 hover:text-green-400 transition-colors ml-1">
                  <Icon name="Eye" size={15} />
                </button>
                <button onClick={() => deleteFile(f.name)}
                  className="text-white/40 hover:text-red-400 transition-colors">
                  <Icon name="Trash2" size={15} />
                </button>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}

