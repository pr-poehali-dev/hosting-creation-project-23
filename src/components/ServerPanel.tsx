// ===================== SERVER PANEL =====================
export default function ServerPanel({ user, onBack, onLogout }: { user: User; onBack: () => void; onLogout: () => void }) {
  const [, forceUpdate] = useState(0);
  const [activeTab, setActiveTab] = useState<SideTab>("console");
  const [selectedServerId, setSelectedServerId] = useState<string | null>(null);
  const [serverStatus, setServerStatus] = useState<Record<string, Server["status"]>>({});

  useEffect(() => subscribeStore(() => forceUpdate(n => n + 1)), []);

  const servers = getServersByUser(user.email);
  const selectedServer = servers.find(s => s.id === selectedServerId) || servers[0] || null;

  const sideItems: { key: SideTab; icon: string; label: string }[] = [
    { key: "console", icon: "Terminal", label: "Консоль" },
    { key: "files", icon: "FolderOpen", label: "Файлы" },
    { key: "settings", icon: "Settings", label: "Настройки" },
    { key: "coowners", icon: "Users", label: "Совладельцы" },
    { key: "database", icon: "Database", label: "База данных" },
    { key: "subdomains", icon: "Globe", label: "Субдомены" },
    { key: "profile", icon: "User", label: "Профиль" },
  ];

  // Monitoring stats (simulated real-time)
  const [cpu, setCpu] = useState(12);
  const [ram, setRam] = useState(256);
  const status = selectedServer ? (serverStatus[selectedServer.id] || selectedServer.status) : "stopped";

  useEffect(() => {
    const t = setInterval(() => {
      if (status === "active") {
        setCpu(Math.floor(10 + Math.random() * 40));
        setRam(Math.floor(200 + Math.random() * 400));
      }
    }, 2000);
    return () => clearInterval(t);
  }, [status]);

  const handleStatusChange = (s: Server["status"]) => {
    if (!selectedServer) return;
    setServerStatus(prev => ({ ...prev, [selectedServer.id]: s }));
  };

  return (
    <div className="min-h-screen bg-[#0a0a0a] text-white flex flex-col">
      {/* Top Bar */}
      <div className="flex items-center gap-4 px-6 py-3 border-b border-white/5 flex-shrink-0"
        style={{ background: "rgba(10,10,10,0.95)", backdropFilter: "blur(16px)" }}>
        <button onClick={onBack} className="text-white/50 hover:text-white transition-colors">
          <Icon name="ArrowLeft" size={20} />
        </button>
        <span className="font-extrabold font-montserrat">Zetix<span className="text-green-400">Hosting</span></span>
        <div className="h-4 w-px bg-white/10"></div>
        <span className="text-white/40 text-sm">Панель управления</span>
        <div className="flex-1" />

        {/* Server selector */}
        {servers.length > 1 && (
          <select value={selectedServerId || ""} onChange={e => setSelectedServerId(e.target.value)}
            className="bg-white/5 border border-white/10 text-white text-sm px-3 py-1.5 rounded-lg focus:outline-none">
            {servers.map(s => <option key={s.id} value={s.id}>{s.planEmoji} {s.planName}</option>)}
          </select>
        )}

        <span className="text-white/40 text-sm hidden md:block">{user.email}</span>
      </div>

      <div className="flex flex-1 overflow-hidden">
        {/* Sidebar */}
        <div className="w-56 flex-shrink-0 border-r border-white/5 flex flex-col" style={{ background: "#0d0d0d" }}>
          {selectedServer && (
            <div className="p-4 border-b border-white/5">
              <div className="text-xs text-white/40 mb-1 uppercase tracking-wider">Сервер</div>
              <div className="flex items-center gap-2">
                <span className="text-lg">{selectedServer.planEmoji}</span>
                <div>
                  <div className="text-white text-sm font-bold font-montserrat">{selectedServer.planName}</div>
                  <div className="text-white/30 text-xs font-mono">{selectedServer.ip}:{selectedServer.port}</div>
                </div>
              </div>
            </div>
          )}

          <nav className="flex-1 p-2 overflow-y-auto">
            {sideItems.map(item => (
              <button key={item.key} onClick={() => setActiveTab(item.key)}
                className="w-full flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm font-medium transition-all duration-150 mb-0.5"
                style={{
                  background: activeTab === item.key ? "rgba(34,197,94,0.12)" : "transparent",
                  color: activeTab === item.key ? "#4ade80" : "rgba(255,255,255,0.5)",
                  borderLeft: activeTab === item.key ? "2px solid #22c55e" : "2px solid transparent",
                }}>
                <Icon name={item.icon} size={16} />
                {item.label}
              </button>
            ))}
          </nav>

          {/* Monitoring mini */}
          {selectedServer && (
            <div className="p-4 border-t border-white/5">
              <div className="text-xs text-white/40 uppercase tracking-wider mb-3">Мониторинг</div>
              <MonitoringBar label="CPU" value={status === "active" ? cpu : 0} max={100} color="#22c55e" />
              <MonitoringBar label="RAM (МБ)" value={status === "active" ? ram : 0} max={1024} color="#3b82f6" />
              <div className="text-xs text-white/30 mt-2">
                <span className={`w-2 h-2 rounded-full inline-block mr-1 ${status === "active" ? "bg-green-400" : "bg-red-500"}`}></span>
                {status === "active" ? "Online" : status === "starting" ? "Starting..." : "Offline"}
              </div>
            </div>
          )}
        </div>

        {/* Main content */}
        <div className="flex-1 overflow-hidden p-6">
          {!selectedServer ? (
            <div className="h-full flex items-center justify-center flex-col gap-4 text-center">
              <div className="text-6xl">🖥</div>
              <h2 className="text-xl font-bold text-white font-montserrat">Нет активных серверов</h2>
              <p className="text-white/40 text-sm max-w-xs">Купите тариф на главной странице, после подтверждения администратором сервер появится здесь</p>
              <button onClick={onBack} className="btn-primary px-6 py-3 rounded-xl text-white font-semibold">
                Перейти к тарифам
              </button>
            </div>
          ) : (
            <div className="h-full">
              {activeTab === "console" && <ConsoleView server={selectedServer} onStatusChange={handleStatusChange} />}
              {activeTab === "files" && <FilesView />}
              {activeTab === "settings" && <SettingsView server={selectedServer} />}
              {activeTab === "coowners" && <CoOwnersView server={selectedServer} />}
              {activeTab === "database" && <DatabaseView />}
              {activeTab === "subdomains" && <SubdomainsView server={selectedServer} />}
              {activeTab === "profile" && <ProfileView user={user} onLogout={onLogout} />}
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
