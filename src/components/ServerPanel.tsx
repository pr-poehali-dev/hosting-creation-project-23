// ===================== CONSOLE =====================
function ConsoleView({ server, onStatusChange }: { server: Server; onStatusChange: (s: Server["status"]) => void }) {
  const [logs, setLogs] = useState<ConsoleLog[]>([
    { time: getTime(), type: "error", text: "Hosting-Minecraft: Сервер помечен как выключенный" }
  ]);
  const [input, setInput] = useState("");
  const [status, setStatus] = useState<Server["status"]>(server.status);
  const bottomRef = useRef<HTMLDivElement>(null);
  const logIntervalRef = useRef<ReturnType<typeof setTimeout> | null>(null);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [logs]);

  const addLog = (log: ConsoleLog) => {
    setLogs(prev => [...prev, { ...log, time: getTime() }]);
  };

  const startServer = () => {
    if (status === "starting" || status === "active") return;
    setStatus("starting");
    onStatusChange("starting");
    let i = 0;
    const run = () => {
      if (i < STARTUP_LOGS.length) {
        addLog(STARTUP_LOGS[i]);
        i++;
        logIntervalRef.current = setTimeout(run, 180 + Math.random() * 200);
      } else {
        setStatus("active");
        onStatusChange("active");
      }
    };
    run();
  };

  const stopServer = () => {
    if (status === "stopped") return;
    setStatus("stopped");
    onStatusChange("stopped");
    STOP_LOGS.forEach((log, i) => {
      setTimeout(() => addLog(log), i * 200);
    });
  };

  const restartServer = () => {
    stopServer();
    setTimeout(() => startServer(), STOP_LOGS.length * 200 + 500);
  };

  const sendCmd = (e: React.FormEvent) => {
    e.preventDefault();
    if (!input.trim()) return;
    addLog({ time: getTime(), type: "info", text: `> ${input}` });
    const cmd = input.toLowerCase().trim();
    if (cmd === "help") {
      addLog({ time: getTime(), type: "success", text: "Доступные команды: help, list, stop, restart, say <msg>" });
    } else if (cmd === "list") {
      addLog({ time: getTime(), type: "info", text: "Игроков онлайн: 0/20" });
    } else if (cmd.startsWith("say ")) {
      addLog({ time: getTime(), type: "success", text: `[Server] ${cmd.slice(4)}` });
    } else {
      addLog({ time: getTime(), type: "warn", text: `Неизвестная команда: ${input}` });
    }
    setInput("");
  };

  const logColor: Record<ConsoleLog["type"], string> = {
    info: "#a0aec0",
    warn: "#f6e05e",
    error: "#fc8181",
    success: "#68d391",
  };

  return (
    <div className="flex flex-col h-full">
      {/* Control buttons */}
      <div className="flex items-center gap-3 mb-4 flex-shrink-0">
        <div className="flex items-center gap-2">
          <span className={`w-2.5 h-2.5 rounded-full ${status === "active" ? "bg-green-400 animate-pulse" : status === "starting" ? "bg-yellow-400 animate-pulse" : "bg-red-500"}`}></span>
          <span className="text-white/50 text-sm">{status === "active" ? "Запущен" : status === "starting" ? "Запускается..." : "Остановлен"}</span>
        </div>
        <div className="flex-1" />
        <button onClick={startServer} disabled={status === "active" || status === "starting"}
          className="flex items-center gap-1.5 px-4 py-2 rounded-lg text-sm font-semibold transition-all disabled:opacity-40"
          style={{ background: "rgba(34,197,94,0.15)", border: "1px solid rgba(34,197,94,0.3)", color: "#4ade80" }}>
          <Icon name="Play" size={14} /> Старт
        </button>
        <button onClick={stopServer} disabled={status === "stopped"}
          className="flex items-center gap-1.5 px-4 py-2 rounded-lg text-sm font-semibold transition-all disabled:opacity-40"
          style={{ background: "rgba(239,68,68,0.15)", border: "1px solid rgba(239,68,68,0.3)", color: "#f87171" }}>
          <Icon name="Square" size={14} /> Стоп
        </button>
        <button onClick={restartServer}
          className="flex items-center gap-1.5 px-4 py-2 rounded-lg text-sm font-semibold transition-all"
          style={{ background: "rgba(251,191,36,0.15)", border: "1px solid rgba(251,191,36,0.3)", color: "#fbbf24" }}>
          <Icon name="RotateCcw" size={14} /> Рестарт
        </button>
      </div>

      {/* Console output */}
      <div className="flex-1 rounded-xl overflow-hidden flex flex-col" style={{ background: "#1a1f2e", border: "1px solid rgba(255,255,255,0.06)" }}>
        <div className="flex items-center gap-2 px-4 py-2 border-b border-white/5" style={{ background: "#151923" }}>
          <div className="w-3 h-3 rounded-full bg-red-500/70"></div>
          <div className="w-3 h-3 rounded-full bg-yellow-500/70"></div>
          <div className="w-3 h-3 rounded-full bg-green-500/70"></div>
          <span className="text-white/30 text-xs ml-2 font-mono">console</span>
        </div>
        <div className="flex-1 overflow-y-auto p-4 font-mono text-sm" style={{ minHeight: 0 }}>
          {logs.map((log, i) => (
            <div key={i} className="flex gap-2 mb-0.5 leading-5">
              <span style={{ color: "#4a5568", flexShrink: 0, fontSize: "11px", marginTop: "1px" }}>{log.time}</span>
              <span style={{ color: logColor[log.type], wordBreak: "break-all" }}>{log.text}</span>
            </div>
          ))}
          <div ref={bottomRef} />
        </div>
        <form onSubmit={sendCmd} className="flex gap-2 p-3 border-t border-white/5">
          <span className="text-green-400 font-mono text-sm self-center">{">"}</span>
          <input value={input} onChange={e => setInput(e.target.value)}
            placeholder="Введите команду..."
            disabled={status !== "active"}
            className="flex-1 bg-transparent text-white font-mono text-sm focus:outline-none placeholder-white/20 disabled:opacity-40"
          />
          <button type="submit" disabled={status !== "active"}
            className="text-green-400 hover:text-green-300 disabled:opacity-40">
            <Icon name="Send" size={15} />
          </button>
        </form>
      </div>
    </div>
  );
}

